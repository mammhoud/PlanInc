#!/usr/bin/env python3
"""Generate per-directory README.md files for PlanInc.

Follows the documentation standard established in `django-fusion`: every project
directory carries a `README.md` describing its role, its contents and its public
API. Content is **derived from the code**, not stubbed:

  * the description is taken from the module doc-comment of the directory's entry
    file when one exists, otherwise from the directory's classified role;
  * `## Contents` is a real inventory of the directory, each source file
    annotated with the first line of its own doc comment;
  * `## Public API` is parsed from the entry file's `export` statements.

Hand-written READMEs are never overwritten. A file is only replaced when it
carries the generator footer in `GENERATOR_MARKER`.

Usage:
    python3 scripts/generate-dir-docs.py            # write/refresh READMEs
    python3 scripts/generate-dir-docs.py --check    # exit 1 if any dir lacks one
    python3 scripts/generate-dir-docs.py --dry-run  # show what would change
"""

